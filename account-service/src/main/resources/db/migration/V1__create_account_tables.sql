CREATE TABLE account.accounts (
  id                  UUID         NOT NULL,
  nickname            VARCHAR(10)  NOT NULL,
  tag                 VARCHAR(10)  NOT NULL,
  email               VARCHAR(320) NOT NULL,
  email_verified_at   TIMESTAMPTZ,
  role                VARCHAR(20)  NOT NULL,
  status              VARCHAR(20)  NOT NULL,
  created_at          TIMESTAMPTZ  NOT NULL,
  updated_at          TIMESTAMPTZ  NOT NULL,
  withdrawn_at        TIMESTAMPTZ,
  recovery_expires_at TIMESTAMPTZ,
  
  CONSTRAINT pk_accounts PRIMARY KEY (id),
  CONSTRAINT uk_accounts_nickname_tag UNIQUE (nickname, tag)
);

-- 탈퇴 계정을 제외한 이메일 중복 방지
CREATE UNIQUE INDEX uk_accounts_email_not_withdrawn
  ON account.accounts (email)
  WHERE status <> 'WITHDRAWN';
  
CREATE TABLE account.account_credentials (
  account_id          UUID         NOT NULL,
  password_hash       VARCHAR(255) NOT NULL,
  password_changed_at TIMESTAMPTZ  NOT NULL,
  
  CONSTRAINT pk_account_credentials PRIMARY KEY (account_id),
  CONSTRAINT fk_account_credentials_account
    FOREIGN KEY (account_id) REFERENCES account.accounts (id)
);

CREATE TABLE account.social_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  account_id       UUID         NOT NULL,
  provider         VARCHAR(30)  NOT NULL,
  provider_user_id VARCHAR(255) NOT NULL,
  linked_at        TIMESTAMPTZ  NOT NULL,
  
  CONSTRAINT pk_social_accounts PRIMARY KEY (id),
  CONSTRAINT fk_social_accounts_account
    FOREIGN KEY (account_id) REFERENCES account.accounts (id),
  CONSTRAINT uk_social_accounts_provider_user UNIQUE (provider, provider_user_id),
  CONSTRAINT uk_social_accounts_account_provider UNIQUE (account_id, provider)
);